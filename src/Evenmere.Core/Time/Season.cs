namespace Evenmere.Core.Time;

/// <summary>The four seasons of the year, in order. A season lasts <see cref="GameTime.DaysPerSeason"/> days.</summary>
public enum Season
{
    /// <summary>The first season of the year.</summary>
    Spring = 0,

    /// <summary>The second season of the year.</summary>
    Summer = 1,

    /// <summary>The third season of the year.</summary>
    Autumn = 2,

    /// <summary>The last season of the year.</summary>
    Winter = 3,
}
