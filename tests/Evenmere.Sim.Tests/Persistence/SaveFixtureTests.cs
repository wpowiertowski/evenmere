using Evenmere.Content;
using Evenmere.Sim.Persistence;
using Evenmere.Sim.Tests.Fixtures;
using Evenmere.Sim.Tests.Integration;
namespace Evenmere.Sim.Tests.Persistence;

/// <summary>
/// The save fixtures in <c>tests/fixtures/saves/</c>, which play two different roles.
/// <list type="bullet">
/// <item><c>v1-slice.evsave</c> is the frozen M1 save: the last version-1 save, restored from the M1 build, and
/// <b>never regenerated</b>. The golden-update path skips it on purpose, so the 0001→0002 migration always has a real
/// version-1 file to prove itself on. Its tests pin the version-1 header, the clean migration at tick 20,000, and
/// deterministic continuation; the migrated-hash check below pins M1 behaviour and must be retired (not regenerated)
/// at the first behaviour change.</item>
/// <item><c>slice-20000.evsave</c> is the current-version golden: regenerated by
/// <c>EVENMERE_UPDATE_GOLDEN=1 dotnet test</c> whenever the state layout changes, and carrying the round-trip checks
/// that need the current format. Every other test that loads a slice save reads one of these two fixtures.</item>
/// </list>
/// </summary>
public sealed class SaveFixtureTests
{
    private readonly ITestOutputHelper _output;

    /// <summary>Initializes a new instance of the <see cref="SaveFixtureTests"/> class.</summary>
    /// <param name="output">The test output.</param>
    public SaveFixtureTests(ITestOutputHelper output)
    {
        _output = output;
    }

    /// <summary>Gets the frozen M1 fixture path. This file is never regenerated.</summary>
    public static string FixturePath => Path.Combine(WorldBuilder.RepoRoot, "tests", "fixtures", "saves", "v1-slice.evsave");

    /// <summary>Gets the current-version golden fixture path. This file is regenerated by the golden updater.</summary>
    public static string CurrentFixturePath => Path.Combine(WorldBuilder.RepoRoot, "tests", "fixtures", "saves", "slice-20000.evsave");

    [Fact]
    public void V1Slice_HasVersion1Header()
    {
        SaveFixtureFormat.ReadEnvelopeVersion(RequireFixture(FixturePath)).ShouldBe((ushort)1);
        SaveFormat.CurrentVersion.ShouldBeGreaterThan((ushort)1);
    }

    [Fact]
    public void V1Slice_LoadsThroughMigrationCleanly_AtTick20000()
    {
        ContentDb content = SiteFinder.Content;
        using FileStream stream = File.OpenRead(RequireFixture(FixturePath));
        (ISimulation simulation, SaveReport report) = SaveGame.Read(stream, content);

        simulation.CurrentTick.ShouldBe(20_000);
        report.IsClean.ShouldBeTrue();
        _output.WriteLine($"fixture tick={simulation.CurrentTick} hash={simulation.ComputeStateHash():x16}");
    }

    [Fact]
    public void V1Slice_LoadTwiceAndContinue2000Ticks_HashesAgree()
    {
        LoadAndContinueTicks(FixturePath, 2_000).ShouldBe(LoadAndContinueTicks(FixturePath, 2_000));
    }

    [Fact]
    public void V1Slice_MigratedHash_MatchesFreshRunTo20000()
    {
        // A behaviour pin, not a golden: while the simulation still behaves as the M1 build did, the migrated M1
        // save reaches the same state as a fresh run to the same tick. The first behaviour change retires this test;
        // it must never be "fixed" by regenerating the frozen fixture.
        ContentDb content = SiteFinder.Content;
        using FileStream stream = File.OpenRead(RequireFixture(FixturePath));
        (ISimulation resumed, _) = SaveGame.Read(stream, content);

        Simulation direct = SliceHarness.RunTo(20_000);
        resumed.ComputeStateHash().ShouldBe(direct.ComputeStateHash());
    }

    [Fact]
    public void CurrentSlice_RoundTrip_StoredHashMatchesComputed()
    {
        if (UpdateRequested)
        {
            RegenerateCurrent();
        }

        ContentDb content = SiteFinder.Content;
        SaveFixtureFormat.ReadEnvelopeVersion(RequireFixture(CurrentFixturePath)).ShouldBe(SaveFormat.CurrentVersion);

        using FileStream stream = File.OpenRead(CurrentFixturePath);
        (ISimulation simulation, SaveReport report) = SaveGame.Read(stream, content);
        simulation.CurrentTick.ShouldBe(20_000);
        report.IsClean.ShouldBeTrue();

        stream.Position = 0;
        SaveGame.ReadStateHash(stream).ShouldBe(simulation.ComputeStateHash());
    }

    private static ulong LoadAndContinueTicks(string path, int ticks)
    {
        using FileStream stream = File.OpenRead(RequireFixture(path));
        (ISimulation simulation, _) = SaveGame.Read(stream, SiteFinder.Content);

        long end = simulation.CurrentTick + ticks;
        for (long tick = simulation.CurrentTick + 1; tick <= end; tick++)
        {
            simulation.Tick();
        }

        return simulation.ComputeStateHash();
    }

    private static string RequireFixture(string path)
    {
        if (!File.Exists(path))
        {
            Assert.Fail($"The save fixture is missing: run with EVENMERE_UPDATE_GOLDEN=1 to generate {path}.");
        }

        return path;
    }

    private static bool UpdateRequested =>
        string.Equals(Environment.GetEnvironmentVariable("EVENMERE_UPDATE_GOLDEN"), "1", StringComparison.Ordinal);

    private static void RegenerateCurrent()
    {
        Directory.CreateDirectory(Path.GetDirectoryName(CurrentFixturePath)!);
        Simulation simulation = SliceHarness.RunTo(20_000);
        using FileStream stream = File.Create(CurrentFixturePath);
        SaveGame.Write(stream, simulation, new SaveMeta(SiteFinder.Content, "fixture", "starter"));
    }
}
